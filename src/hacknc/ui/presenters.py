def persona_for(username: str) -> Persona | None:
    return next((p for p in PERSONAS if p.username == username), None)


def can_log_in_as(username: str) -> bool:
    """A known demo login (used as Keycloak's login hint)."""
    return persona_for(username) is not None or any(u == username for u, *_ in PORTAL_PATIENTS)


def primary_role(claims: TokenClaims) -> str:
    """The hospital role to show on a badge (ignores Keycloak's built-in roles)."""
    return next(iter(sorted(claims.realm_roles & set(ROLES))), "unknown")


def home_for(role: str) -> str:
    """Where each role starts. A user with no hospital role goes back to the landing page
    (which explains why) instead of bouncing between guarded pages."""
    return {"admin": "/admin", "patient": "/portal", "physician": "/ward",
            "nurse": "/ward"}.get(role, "/?error=no-role")


