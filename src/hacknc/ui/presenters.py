def grafana_trace_url(grafana_url: str, trace_id: str, span_id: str = "") -> str:
    """Deep link that opens a trace in Grafana Explore (Tempo datasource uid ``tempo``).

    With ``span_id`` the trace view opens with that span selected and expanded, so a step in
    the activity feed lands on exactly the span it was built from.
    """
    panes: dict[str, Any] = {
        "t": {
            "datasource": "tempo",
            "queries": [{
                "refId": "A",
                "datasource": {"type": "tempo", "uid": "tempo"},
                "queryType": "traceql",
                "query": trace_id,
            }],
            "range": {"from": "now-1h", "to": "now"},
        }
    }
    if span_id:
        panes["t"]["panelsState"] = {"trace": {"spanId": span_id}}
    encoded = quote(json.dumps(panes, separators=(",", ":")), safe="")
    return f"{grafana_url.rstrip('/')}/explore?schemaVersion=1&panes={encoded}"


